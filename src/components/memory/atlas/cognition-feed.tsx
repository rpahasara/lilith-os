export const KIND: Record<AtlasEvent["type"], { label: string; icon: LucideIcon }> = {
  "memory.learned": { label: "Learned", icon: Sparkles },
  "memory.linked": { label: "Linked", icon: GitMerge },
  "memory.reinforced": { label: "Reinforced", icon: ArrowUpRight },
  "memory.recalled": { label: "Recalled", icon: Route },
  // real memory: differences between two snapshots of the read model
  "record.observed": { label: "Newly observed", icon: Sparkles },
  "record.changed": { label: "Changed", icon: ArrowUpRight },
  "record.withdrawn": { label: "No longer in the read model", icon: X },
  "link.observed": { label: "Association observed", icon: GitMerge },
  "link.withdrawn": { label: "Association gone", icon: X },
};

export function ago(at: number, now: number) {
  const s = Math.max(0, Math.round((now - at) / 1000));
  if (s < 5) return "now";
  if (s < 60) return `${s}s`;
  return `${Math.floor(s / 60)}m`;
}

/** A clock that ticks every few seconds so relative times stay honest. */
export function useTick(ms: number) {
  const [now, setNow] = useState(() => Date.now());
  useEffect(() => {
    const id = setInterval(() => setNow(Date.now()), ms);
    return () => clearInterval(id);
  }, [ms]);
  return now;
}

/**
 * Activity feed — what the simulated mind is doing right now. Every row is an
 * AtlasEvent that just passed through the store; today all of them come from
 * the synthetic simulation, and the panel says so.
 */
export function CognitionFeed({
  state,
  running,
  onToggle,
  onSelect,
  onClose,
  className,
}: {
  state: AtlasState;
  running: boolean;
  onToggle: () => void;
  onSelect: (id: string) => void;
  onClose?: () => void;
  className?: string;
}) {
  const now = useTick(5000);
  const { session } = state;

  return (
    <GlassCard strong animated={false} className={cn("flex min-h-0 flex-col", className)}>
      <div className="flex items-center justify-between gap-2 px-5 pt-4">
        <div className="mr-auto flex items-center gap-2.5">
          <span className={cn("status-dot inline-block h-1.5 w-1.5 rounded-full", running ? "bg-wine-bright text-wine-bright" : "bg-ink-faint text-transparent")} />
          <p className="eyebrow">Activity</p>
          <span
            className="inline-flex items-center gap-1 rounded-full border border-amber/25 bg-amber/10 px-1.5 py-px font-mono text-[8px] uppercase tracking-[0.12em] text-amber"
            title="Every event here is generated by the prototype's simulation, not by Lilith's real memory."
          >
            <FlaskConical className="h-2.5 w-2.5" />
            Simulated
          </span>
        </div>
        <button
          type="button"
          onClick={onToggle}
          aria-pressed={running}
          aria-label={running ? "Pause the simulation" : "Resume the simulation"}
          className="inline-flex items-center gap-1.5 rounded-full border border-white/[0.08] bg-white/[0.03] px-2.5 py-1 font-mono text-[10px] uppercase tracking-[0.12em] text-ink-muted transition-colors hover:border-white/20 hover:text-ink"
        >
          {running ? <Pause className="h-2.5 w-2.5" /> : <Play className="h-2.5 w-2.5" />}
          {running ? "Running" : "Paused"}
        </button>
        {onClose && <CloseButton label="Close activity feed" onClick={onClose} />}
      </div>

      <div className="grid grid-cols-4 gap-1.5 px-5 pt-3">
        {[
          { label: "Learned", value: session.learned },
          { label: "Linked", value: session.linked },
          { label: "Reinforced", value: session.reinforced },
          { label: "Recalled", value: session.recalled },
        ].map((m) => (
          <div key={m.label} className="rounded-lg border border-white/[0.05] bg-white/[0.02] px-2 py-1.5">
            <p className="font-mono text-sm font-semibold text-ink">{m.value}</p>
            <p className="font-mono text-[8px] uppercase tracking-[0.12em] text-ink-faint">{m.label}</p>
          </div>
        ))}
      </div>

      <div className="scroll-area relative mt-3 min-h-0 flex-1 overflow-y-auto px-3 pb-3">
        {state.activity.length === 0 ? (
          <div className="px-2 py-6 text-center">
            <p className="text-xs text-ink-muted">{running ? "Listening for the first thought…" : "Simulation paused."}</p>
            <p className="mt-1 text-[11px] leading-relaxed text-ink-faint">
              Synthetic memories arrive every few seconds. Watch a region brighten as it learns.
            </p>
          </div>
        ) : (
          <ul className="space-y-0.5">
            <AnimatePresence initial={false}>
              {state.activity.slice(0, 14).map((item) => (
                <FeedRow key={item.id} item={item} now={now} onSelect={onSelect} />
              ))}
            </AnimatePresence>
          </ul>
        )}
      </div>
    </GlassCard>
  );
}

export function FeedRow({
  item,
  now,
  onSelect,
}: {
  item: AtlasActivity;
  now: number;
  onSelect: (id: string) => void;
}) {
  const region = REGION_BY_ID[item.region];
  const kind = KIND[item.type];
  const Icon = kind.icon;
  return (
    <motion.li
      layout
      initial={{ opacity: 0, y: -10, filter: "blur(4px)" }}
      animate={{ opacity: 1, y: 0, filter: "blur(0px)" }}
      exit={{ opacity: 0 }}
      transition={{ duration: 0.45, ease: [0.22, 1, 0.36, 1] }}
    >
      <button
        type="button"
        disabled={!item.nodeId}
        onClick={() => item.nodeId && onSelect(item.nodeId)}
        className="group flex w-full items-start gap-2.5 rounded-lg px-2 py-2 text-left transition-colors hover:bg-white/[0.04]"
      >
        <span
          className="mt-0.5 grid h-6 w-6 shrink-0 place-items-center rounded-lg"
          style={{ color: region.color, background: `${region.color}1a` }}
        >
          <Icon className="h-3 w-3" />
        </span>
        <span className="min-w-0 flex-1">
          <span className="line-clamp-2 text-xs leading-snug text-ink-muted group-hover:text-ink">{item.text}</span>
          <span className="mt-0.5 block font-mono text-[9px] uppercase tracking-[0.12em] text-ink-faint">
            {kind.label} · {region.label}
          </span>
        </span>
        <span className="mt-0.5 shrink-0 font-mono text-[10px] text-ink-faint">{ago(item.at, now)}</span>
      </button>
    </motion.li>
  );
}

/** Timeline mode: the memories that existed as of the scrubbed moment, newest first. */
export function GrowthLog({
  nodes,
  asOf,
  onSelect,
  onClose,
  className,
}: {
  nodes: AtlasNode[];
  asOf: number;
  onSelect: (id: string) => void;
  onClose?: () => void;
  className?: string;
}) {
  const visible = nodes
    .filter((n) => n.born <= asOf)
    .sort((a, b) => (b.createdAt ?? 0) - (a.createdAt ?? 0))
    .slice(0, 16);
  return (
    <GlassCard strong animated={false} className={cn("flex min-h-0 flex-col", className)}>
      <div className="flex items-center justify-between gap-2 px-5 pt-4">
        <p className="eyebrow mr-auto">Most recently learned</p>
        <span className="font-mono text-[10px] text-ink-faint">as of the marker</span>
        {onClose && <CloseButton label="Close growth log" onClick={onClose} />}
      </div>
      <ul className="scroll-area mt-2 min-h-0 flex-1 space-y-0.5 overflow-y-auto px-3 pb-3">
        {visible.length === 0 && (
          <li className="px-2 py-6 text-center text-xs text-ink-faint">Nothing learned yet at this point.</li>
        )}
        {visible.map((n) => {
          const region = REGION_BY_ID[n.region];
          return (
            <li key={n.id}>
              <button
                type="button"
                onClick={() => onSelect(n.id)}
                className="group flex w-full items-start gap-2.5 rounded-lg px-2 py-1.5 text-left transition-colors hover:bg-white/[0.04]"
              >
                <span
                  className="mt-1.5 h-1.5 w-1.5 shrink-0 rounded-full"
                  style={{ background: region.color, boxShadow: `0 0 8px ${region.color}` }}
                />
                <span className="min-w-0 flex-1">
                  <span className="line-clamp-2 text-xs text-ink-muted group-hover:text-ink">{n.title}</span>
                  <span className="mt-0.5 block font-mono text-[9px] uppercase tracking-[0.12em] text-ink-faint">
                    {region.label} ·{" "}
                    {new Date(n.createdAt ?? 0).toLocaleDateString("en-GB", { day: "numeric", month: "short" })}
                  </span>
                </span>
              </button>
            </li>
          );
        })}
      </ul>
    </GlassCard>
  );
}

export function CloseButton({ label, onClick }: { label: string; onClick: () => void }) {
  return (
    <button
      type="button"
      onClick={onClick}
      aria-label={label}
      className="grid h-6 w-6 shrink-0 place-items-center rounded-full bg-white/[0.06] text-ink-muted transition-colors hover:text-ink"
    >
      <X className="h-3 w-3" />
    </button>
  );
}

/**
 * The latest thought, shown for a few seconds and then gone — the brain's
 * activity surfaced without a permanent panel. Clicking it opens that memory.
 */
export function ThoughtTicker({
  activity,
  onSelect,
  className,
  origin = "synthetic",
}: {
  /** real memory: the row names an observed difference, not a thought. */
  origin?: "synthetic" | "real";
  activity: AtlasActivity[];
  onSelect: (id: string) => void;
  className?: string;
}) {
  const latest = activity[0];
  const [shown, setShown] = useState<string | null>(null);

  useEffect(() => {
    if (!latest) return;
    setShown(latest.id);
    const id = setTimeout(() => setShown(null), 6500);
    return () => clearTimeout(id);
  }, [latest]);

  const item = latest && shown === latest.id ? latest : null;
  const region = item ? REGION_BY_ID[item.region] : null;
  const kind = item ? KIND[item.type] : null;

  return (
    <div className={cn("pointer-events-none", className)} aria-live="polite">
      <AnimatePresence mode="wait">
        {item && region && kind && (
          <motion.button
            key={item.id}
            type="button"
            disabled={!item.nodeId}
            onClick={() => item.nodeId && onSelect(item.nodeId)}
            initial={{ opacity: 0, y: 8, filter: "blur(6px)" }}
            animate={{ opacity: 1, y: 0, filter: "blur(0px)" }}
            exit={{ opacity: 0, y: -6, filter: "blur(6px)" }}
            transition={{ duration: 0.5, ease: [0.22, 1, 0.36, 1] }}
            className="pointer-events-auto flex max-w-full items-center gap-2.5 rounded-full border border-white/[0.08] bg-black/35 py-1.5 pl-2 pr-3.5 text-left backdrop-blur-md transition-colors hover:border-white/20"
          >
            <span
              className="grid h-5 w-5 shrink-0 place-items-center rounded-full"
              style={{ color: region.color, background: `${region.color}24` }}
            >
              <kind.icon className="h-2.5 w-2.5" />
            </span>
            <span className="min-w-0">
              <span className="flex items-center gap-1.5 font-mono text-[8px] uppercase tracking-[0.16em]" style={{ color: region.color }}>
                {kind.label} · {region.label}
                {origin === "real" ? (
                  <span className="flex items-center gap-0.5 text-cyan-bright/90">
                    <Database className="h-2 w-2" />
                    snapshot
                  </span>
                ) : (
                  <span className="flex items-center gap-0.5 text-amber/90">
                    <FlaskConical className="h-2 w-2" />
                    simulated
                  </span>
                )}
              </span>
              <span className="block truncate text-[11px] leading-tight text-ink-muted">{item.text}</span>
            </span>
          </motion.button>
        )}
      </AnimatePresence>
    </div>
  );
}
